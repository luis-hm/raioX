const assert = require("node:assert/strict");
const fs = require("node:fs");
const Module = require("node:module");
const ts = require("typescript");

const source = fs.readFileSync(require.resolve("./results.ts"), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = new Module(require.resolve("./results.ts"), module);
mod.filename = require.resolve("./results.ts"); mod.paths = module.paths;
const originalRequire = mod.require.bind(mod);
mod.require = name => name === "server-only" ? {} : originalRequire(name);
mod._compile(compiled, mod.filename);
const result = mod.exports.loadResults();
assert.equal(result.totalExecutions, 250);
assert.equal(result.means.length, 50);
assert.equal(result.tests.length, 28);
const lookup = method => result.means.find(row => row.grupo === "N" && row.fracao === 1 && row.metodo === method);
assert.ok(Math.abs(lookup("B1").media - 0.5414837004678799) < 1e-12);
assert.ok(Math.abs(lookup("B2").media - 0.4272296057352335) < 1e-12);
assert.ok(Math.abs(lookup("P").media - 0.4952451475527933) < 0.002);
assert.ok(result.tests.some(row => row.grupo === "N" && row.comparacao === "P - B2" && row.veredito.includes("não significativa")));
assert.ok(result.cost.B2 > 0 && result.cost.P > 0);
console.log("Corrected results contract PASS");
